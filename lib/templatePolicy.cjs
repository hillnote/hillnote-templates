'use strict';
// Workspace template policy — what a template may contain, its limits, and the
// shape of template.json. docs/WORKSPACE_TEMPLATES.md §1–§3 is the contract.
//
// PURE CommonJS, no requires: this file is canonical HERE and vendored
// byte-identical into hillnote-templates/lib/templatePolicy.cjs (run
// `node scripts/sync-template-policy.js`). The repo's CI validates every template
// with it and the app enforces it again at install — the app is the boundary
// that matters, so CI being at least as strict is what keeps a merged template
// installable. The sync-path folding (case, Unicode, 8.3 aliases, NTFS streams)
// is not re-implemented: callers inject syncRules' predicates.
//
//   const policy = createTemplatePolicy(require('../../lib/syncRules'))
//   policy.classify('documents/Plan.md', { pluginIds: [] })  → { allow: true, kind: 'file' }
//   policy.classify('local-triggers.json')                    → { allow: false, reason: 'not-allowed' }

const POLICY_VERSION = 1;
const FORMAT_VERSION = 1;

const LIMITS = Object.freeze({
  maxFiles: 5000,
  maxTotalBytes: 100 * 1024 * 1024,
  maxFileBytes: 25 * 1024 * 1024,
  // STORE-only zips: content plus ~(76 + 2·name) bytes of headers per entry.
  maxZipBytes: 110 * 1024 * 1024,
  maxPathLength: 400,
  maxSegmentLength: 200,
});

const TEMPLATE_ID_RE = /^[a-z0-9][a-z0-9-]{1,63}$/;
const PLUGIN_ID_RE = /^[a-z0-9][a-z0-9-]{0,63}$/;
const SEMVER_RE = /^(0|[1-9]\d{0,5})\.(0|[1-9]\d{0,5})\.(0|[1-9]\d{0,5})$/;
const APP_VERSION_RE = /^\d{1,6}(\.\d{1,12}){0,3}$/;
const SHA256_RE = /^[0-9a-f]{64}$/;
const COLOR_KEY_RE = /^[A-Za-z][A-Za-z0-9_-]{0,31}$/;
// The week a template's sample dates were written around (templateTransforms
// anchorShiftDays moves them to the install week).
const DATE_ANCHOR_RE = /^(20\d\d|2100)-(0[1-9]|1[0-2])-(0[1-9]|[12]\d|3[01])$/;

// The 10 setups of the website (src/content/setups.js) and onboarding
// (src/onboarding/steps.js). setups[0] picks the website band.
const SETUP_KEYS = Object.freeze([
  'solo-builder', 'code', 'design', 'product', 'writing',
  'creator', 'marketing', 'research', 'dungeon-master', 'fitness',
]);

// Root-level files a template may carry. Everything else at the root is
// generated for the new workspace (readme.md, agents.md, CLAUDE.md) or is
// machine state (local-triggers.json runs shell commands; .auto-organise.json
// is run state; settings live in the app).
const ROOT_FILES = new Set([
  'dashboard.json',
  'documents-registry.json',
  'ai_prompt_overrides.json',
  'workspace-properties.json',
  'variables.md',
]);
const COVER_RE = /^cover\.(png|jpg|jpeg|gif|webp|avif)$/;

// Files that are merged into what the target already has instead of being
// created exclusively — templateTransforms.js owns the merge rules.
const MERGE_FILES = new Set([
  'dashboard.json',
  'documents-registry.json',
  'ai_prompt_overrides.json',
  'workspace-properties.json',
  'variables.md',
  'resources/html/tool_registry.json',
]);

// documents/ files that are personal (the notepad never syncs either) or
// regenerated by the app. Compared folded.
const GENERATED_DOCUMENTS = new Set(['documents/notepad.md', 'documents/topics.md']);

// Win32 device names, with or without an extension (CON.md opens the console).
const WINDOWS_RESERVED_RE = /^(con|prn|aux|nul|com[0-9¹²³]|lpt[0-9¹²³]|conin\$|conout\$)(\..*)?$/i;
// Characters Windows refuses in a name — ':' also closes the NTFS-stream door.
const WINDOWS_INVALID_RE = /[<>:"|?*]/;
const CONTROL_RE = /[\u0000-\u001f\u007f]/;

const ENCRYPTED_PREFIX = '---HILLNOTE-ENC-V1---';

const allow = (kind) => ({ allow: true, kind });
const deny = (reason) => ({ allow: false, reason });

/**
 * @param {object} rules  syncRules (or the vendored copy): { isStrictDeniedPath, foldPath }
 */
function createTemplatePolicy(rules) {
  if (!rules || typeof rules.isStrictDeniedPath !== 'function' || typeof rules.foldPath !== 'function') {
    throw new Error('createTemplatePolicy needs syncRules.isStrictDeniedPath and syncRules.foldPath');
  }
  const { isStrictDeniedPath, foldPath } = rules;

  /**
   * One workspace-relative path (forward slashes) → { allow, kind } where
   * kind is 'file' (exclusive create) or 'merge'; or { allow: false, reason }.
   * @param {string} rel
   * @param {{ pluginIds?: string[] }} [opts] the entry's plugin references
   */
  function classify(rel, opts = {}) {
    const pluginIds = Array.isArray(opts.pluginIds) ? opts.pluginIds : [];
    if (typeof rel !== 'string' || rel.length === 0) return deny('empty');
    if (rel.length > LIMITS.maxPathLength) return deny('too-long');
    if (CONTROL_RE.test(rel) || rel.includes('\\')) return deny('bad-char');
    let nfc;
    try { nfc = rel.normalize('NFC'); } catch { return deny('not-nfc'); }
    if (nfc !== rel) return deny('not-nfc');
    if (rel.startsWith('/') || /^[a-zA-Z]:/.test(rel)) return deny('absolute');

    const parts = rel.split('/');
    for (const part of parts) {
      if (part === '' || part === '.' || part === '..') return deny('traversal');
      if (part.startsWith('.')) return deny('dot-segment');
      if (part.length > LIMITS.maxSegmentLength) return deny('too-long');
      if (WINDOWS_INVALID_RE.test(part)) return deny('bad-char');
      if (/[. ]$/.test(part)) return deny('trailing-dot-space');
      if (WINDOWS_RESERVED_RE.test(part)) return deny('reserved-name');
    }
    if (isStrictDeniedPath(rel)) return deny('sync-denied');

    const top = parts[0];
    if (parts.length === 1) {
      if (ROOT_FILES.has(top)) return allow(MERGE_FILES.has(top) ? 'merge' : 'file');
      if (COVER_RE.test(top)) return allow('file');
      return deny('not-allowed');
    }

    if (top === 'documents') {
      if (GENERATED_DOCUMENTS.has(foldPath(rel))) return deny('generated');
      return allow('file');
    }

    if (top === 'resources') {
      const name = parts[parts.length - 1].toLowerCase();
      // Per-tool settings can hold the author's API keys.
      if (name === 'tool.settings.json') return deny('tool-settings');
      if (parts[1] === 'html' && name.endsWith('.settings.json')) return deny('tool-settings');
      if (rel === 'resources/html/tool_registry.json') return allow('merge');
      return allow('file');
    }

    if (top === 'plugins') {
      const id = parts[1];
      if (!PLUGIN_ID_RE.test(id) || !pluginIds.includes(id)) return deny('plugin-not-listed');
      if (parts.length < 3) return deny('not-allowed');
      // Plugin runtime state (config.json, storage/) is per-user.
      if (parts[2] === 'storage') return deny('plugin-state');
      if (parts.length === 3 && parts[2] === 'config.json') return deny('plugin-state');
      return allow('file');
    }

    return deny('not-allowed');
  }

  /**
   * Paths that would land on top of each other on a case-insensitive / Unicode-
   * folding filesystem, plus file-vs-folder clashes ('a.md' as a file and as a
   * folder). → [{ path, reason }] for every offending path (empty = fine).
   */
  function findCollisions(paths) {
    const issues = [];
    const byFold = new Map();
    for (const p of paths) {
      const key = foldPath(p);
      if (byFold.has(key)) {
        issues.push({ path: p, reason: 'fold-collision' });
        issues.push({ path: byFold.get(key), reason: 'fold-collision' });
      } else {
        byFold.set(key, p);
      }
    }
    for (const p of paths) {
      const parts = foldPath(p).split('/');
      for (let i = 1; i < parts.length; i++) {
        const prefix = parts.slice(0, i).join('/');
        if (byFold.has(prefix)) {
          issues.push({ path: p, reason: 'file-folder-clash' });
          break;
        }
      }
    }
    // One report per path.
    const seen = new Set();
    return issues.filter((i) => (seen.has(i.path) ? false : (seen.add(i.path), true)));
  }

  return { classify, findCollisions };
}

/** True when a file's leading bytes are a Hillnote encrypted-document envelope. */
function isEncryptedContent(data) {
  if (data == null) return false;
  const head = typeof data === 'string' ? data.slice(0, 64) : Buffer.from(data.subarray(0, 64)).toString('utf8');
  return head.replace(/^﻿/, '').trimStart().startsWith(ENCRYPTED_PREFIX);
}

// ---- template.json ---------------------------------------------------------

const str = (v) => (typeof v === 'string' ? v.trim() : '');

/**
 * Validate a template.json object. Returns { ok, errors, manifest } — manifest
 * is the normalized copy (trimmed strings, defaults filled, unknown keys
 * dropped) whenever ok.
 * @param {object} raw
 * @param {{ folderId?: string, colorKeys?: string[] }} [opts]
 */
function validateTemplateManifest(raw, opts = {}) {
  const errors = [];
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) {
    return { ok: false, errors: ['template.json must be a JSON object'], manifest: null };
  }
  const err = (m) => errors.push(m);

  if (raw.formatVersion !== FORMAT_VERSION) err(`formatVersion must be ${FORMAT_VERSION}`);

  const id = str(raw.id);
  if (!TEMPLATE_ID_RE.test(id)) err('id must match ^[a-z0-9][a-z0-9-]{1,63}$');
  if (opts.folderId !== undefined && id !== opts.folderId) err(`id "${id}" must equal the folder name "${opts.folderId}"`);

  const version = str(raw.version);
  if (!SEMVER_RE.test(version)) err('version must be semver x.y.z');

  const name = str(raw.name);
  if (!name || name.length > 60) err('name is required (1–60 characters)');
  const tagline = str(raw.tagline);
  if (!tagline || tagline.length > 140 || /\n/.test(tagline)) err('tagline is required (one line, 1–140 characters)');
  const description = str(raw.description);
  if (!description || description.length > 2000) err('description is required (≤ 2000 characters)');

  let setups = [];
  if (raw.setups !== undefined) {
    if (!Array.isArray(raw.setups) || raw.setups.some((s) => !SETUP_KEYS.includes(s))) {
      err(`setups must be a subset of: ${SETUP_KEYS.join(', ')}`);
    } else {
      setups = [...new Set(raw.setups)];
    }
  }

  let tags = [];
  if (raw.tags !== undefined) {
    if (!Array.isArray(raw.tags) || raw.tags.length > 8 || raw.tags.some((t) => typeof t !== 'string' || !t.trim() || t.trim().length > 24)) {
      err('tags must be ≤ 8 strings of ≤ 24 characters');
    } else {
      tags = raw.tags.map((t) => t.trim());
    }
  }

  if (raw.featured !== undefined && typeof raw.featured !== 'boolean') err('featured must be a boolean');

  const author = raw.author && typeof raw.author === 'object' ? raw.author : null;
  const authorName = str(author?.name);
  const authorUrl = str(author?.url);
  if (!authorName || authorName.length > 60) err('author.name is required (≤ 60 characters)');
  if (authorUrl && !/^https:\/\/[^\s]+$/.test(authorUrl)) err('author.url must be an https URL');

  if (raw.license !== 'MIT') err('license must be "MIT"');

  const credits = str(raw.credits);
  if (credits.length > 1000) err('credits must be ≤ 1000 characters');

  const minAppVersion = str(raw.minAppVersion);
  if (minAppVersion && !APP_VERSION_RE.test(minAppVersion)) err('minAppVersion must be a dotted numeric version');

  const open = str(raw.open);
  if (open && (!open.startsWith('documents/') || open.includes('..') || open.includes('\\'))) {
    err('open must be a path under documents/');
  }

  const overview = str(raw.overview);
  if (overview.length > 300) err('overview must be ≤ 300 characters');

  const dateAnchor = str(raw.dateAnchor);
  if (dateAnchor && (!DATE_ANCHOR_RE.test(dateAnchor) || Number.isNaN(Date.parse(`${dateAnchor}T00:00:00Z`))
      || new Date(`${dateAnchor}T00:00:00Z`).toISOString().slice(0, 10) !== dateAnchor)) {
    err('dateAnchor must be a real YYYY-MM-DD date');
  }

  const color = str(raw.color);
  if (color && Array.isArray(opts.colorKeys) && !opts.colorKeys.includes(color)) err(`color must be one of: ${opts.colorKeys.join(', ')}`);
  // TAG_COLORS keys (src/lib/colors.js) are camelCase or snake_case: hotPink, rose_gold.
  if (color && !COLOR_KEY_RE.test(color)) err('color must be a TAG_COLORS key');

  let plugins = [];
  if (raw.plugins !== undefined) {
    if (!Array.isArray(raw.plugins) || raw.plugins.length > 20) {
      err('plugins must be a list (≤ 20)');
    } else {
      const seen = new Set();
      for (const p of raw.plugins) {
        const pid = str(p?.id);
        const pver = str(p?.version);
        const psha = str(p?.sha256);
        if (!PLUGIN_ID_RE.test(pid)) { err(`plugin id "${pid}" is invalid`); continue; }
        if (seen.has(pid)) { err(`plugin "${pid}" is listed twice`); continue; }
        seen.add(pid);
        if (!SEMVER_RE.test(pver)) err(`plugin "${pid}" needs a semver version`);
        if (!SHA256_RE.test(psha)) err(`plugin "${pid}" needs the release archive's sha256`);
        plugins.push({ id: pid, version: pver, sha256: psha });
      }
    }
  }

  const mediaPath = (v) => typeof v === 'string' && /^media\/[A-Za-z0-9][A-Za-z0-9._-]{0,80}\.(webp|png|jpg|jpeg|avif)$/.test(v);
  if (!mediaPath(raw.icon)) err('icon must be a media/ image path (media/icon.webp)');
  if (raw.hero !== undefined && raw.hero !== null && !mediaPath(raw.hero)) err('hero must be a media/ image path');
  let screenshots = [];
  if (raw.screenshots !== undefined) {
    if (!Array.isArray(raw.screenshots) || raw.screenshots.length > 6 || raw.screenshots.some((s) => !mediaPath(s))) {
      err('screenshots must be ≤ 6 media/ image paths');
    } else {
      screenshots = raw.screenshots;
    }
  }

  if (errors.length) return { ok: false, errors, manifest: null };
  return {
    ok: true,
    errors: [],
    manifest: {
      formatVersion: FORMAT_VERSION,
      id, version, name, tagline, description, setups, tags,
      featured: raw.featured === true,
      author: authorUrl ? { name: authorName, url: authorUrl } : { name: authorName },
      license: 'MIT',
      credits,
      minAppVersion: minAppVersion || null,
      open: open || null,
      overview,
      dateAnchor: dateAnchor || null,
      color: color || null,
      plugins,
      icon: raw.icon,
      hero: raw.hero || null,
      screenshots,
    },
  };
}

// ---- includes (what a listing says it brings) -------------------------------

const DOC_SUFFIXES = [['.slides.md', 'slides'], ['.canvas.md', 'canvases'], ['.moodboard.md', 'moodboards']];

/**
 * Count what a set of workspace files brings (docs/WORKSPACE_TEMPLATES.md §2).
 * @param {string[]} paths        allowed workspace-relative paths
 * @param {(rel: string) => string|null} [readText]  for ai_prompt_overrides.json
 * @param {string[]} [pluginIds]
 */
function computeIncludes(paths, readText, pluginIds = []) {
  const markerDirs = (marker) => paths
    .filter((p) => p.startsWith('documents/') && p.endsWith(`/${marker}`))
    .map((p) => p.slice(0, -(marker.length + 1)));
  const databases = markerDirs('database.json');
  const sheets = markerDirs('sheet.json');
  const libraries = markerDirs('library.json');
  const containers = [...databases, ...sheets, ...libraries].map((d) => `${d}/`);

  const counts = { documents: 0, databases: databases.length, sheets: sheets.length, slides: 0, canvases: 0, moodboards: 0, tools: 0, plugins: pluginIds.length, libraries: libraries.length, recipes: 0 };
  for (const p of paths) {
    if (!p.startsWith('documents/') || !p.endsWith('.md')) continue;
    const suffix = DOC_SUFFIXES.find(([s]) => p.endsWith(s));
    if (suffix) { counts[suffix[1]] += 1; continue; }
    if (containers.some((c) => p.startsWith(c))) continue;
    counts.documents += 1;
  }
  counts.tools = listToolEntries(paths).length;

  if (typeof readText === 'function' && paths.includes('ai_prompt_overrides.json')) {
    try {
      const parsed = JSON.parse(readText('ai_prompt_overrides.json') || '{}');
      counts.recipes = Array.isArray(parsed?.overrides) ? parsed.overrides.length : 0;
    } catch { counts.recipes = 0; }
  }
  return counts;
}

/**
 * The HTML tools among a set of paths, the way the app lists them: each
 * first-level folder under resources/html/ holding an .html file is one tool,
 * and every loose resources/html/*.html file is one tool. → sorted list of the
 * tool folder or file paths.
 */
function listToolEntries(paths) {
  const tools = new Set();
  for (const p of paths) {
    if (!p.startsWith('resources/html/') || !/\.html?$/i.test(p)) continue;
    const rest = p.slice('resources/html/'.length).split('/');
    tools.add(rest.length === 1 ? p : `resources/html/${rest[0]}`);
  }
  return [...tools].sort();
}

